// Lookup with light normalization — lowercases, strips trailing
// punctuation/contractions like "wat's" → "wat".
export function lookupAfrikaans(word: string): string | null {
  const cleaned = word.toLowerCase().replace(/^[^a-zäëïöüâêîôûáéíóú]+|[^a-zäëïöüâêîôûáéíóú]+$/giu, "");
  if (!cleaned) return null;
  if (cleaned in AF_TO_EN) return AF_TO_EN[cleaned];
  // Drop trailing apostrophe contraction: "wat's" → "wat".
  const stripped = cleaned.replace(/'[a-z]+$/, "");
  if (stripped !== cleaned && stripped in AF_TO_EN) return AF_TO_EN[stripped];
  return null;
}
